// Writes src/ui/caption-faces.ts: every face of the 18 caption fonts (weight 400, each subset with
// its unicode-range), read from the @fontsource packages' 400.css, for drawing captions on a canvas.
// Run after changing the font packages: node scripts/make-caption-faces.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'))
const packages = Object.keys(pkg.dependencies).filter((name) => name.startsWith('@fontsource/'))

const imports = []
const families = []
let n = 0
for (const name of packages.sort()) {
  const css = fs.readFileSync(path.join(ROOT, 'node_modules', name, '400.css'), 'utf8')
  let family = null
  const faces = []
  for (const block of css.matchAll(/@font-face\s*{([^}]*)}/g)) {
    const body = block[1]
    const fam = /font-family:\s*'([^']+)'/.exec(body)[1]
    if (family && fam !== family) throw new Error(`${name}: two families`)
    family = fam
    if (!/font-weight:\s*400;/.test(body) || !/font-style:\s*normal;/.test(body)) throw new Error(`${name}: not 400 normal`)
    const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(body)[1]
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1].trim() ?? 'U+0-10FFFF'
    const id = `f${n++}`
    imports.push(`import ${id} from '${name}/files/${file}?url'`)
    faces.push(`    { url: ${id}, range: '${range}' }`)
  }
  families.push(`  '${family}': [\n${faces.join(',\n')}\n  ]`)
}

const out = `// GENERATED by scripts/make-caption-faces.mjs from the @fontsource packages' 400.css: every face
// of the caption fonts, weight 400, each subset with the characters it covers.
${imports.join('\n')}

export const CAPTION_FACES: Record<string, { url: string; range: string }[]> = {
${families.join(',\n')}
}
`
fs.writeFileSync(path.join(ROOT, 'src', 'ui', 'caption-faces.ts'), out)
console.log(`${packages.length} fonts, ${n} faces`)
